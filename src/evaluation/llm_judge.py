from __future__ import annotations
import os
import re
import json
from typing import Dict, Any, List, Optional
from pydantic import BaseModel, Field
from src.config import config

class JudgeScore(BaseModel):
    correctness: float = Field(..., ge=1.0, le=5.0)
    groundedness: float = Field(..., ge=1.0, le=5.0)
    helpfulness: float = Field(..., ge=1.0, le=5.0)
    brand_consistency: float = Field(..., ge=1.0, le=5.0)
    safety: float = Field(..., ge=1.0, le=5.0)
    average_score: float = 0.0
    reasoning: str

    def model_post_init(self, __context: Any) -> None:
        self.average_score = round(
            (self.correctness + self.groundedness + self.helpfulness + self.brand_consistency + self.safety) / 5.0,
            2
        )

JUDGE_RUBRIC_PROMPT = """You are an impartial, senior QA auditor evaluating customer support responses generated by an AI support agent.
Evaluate the AI's response to the customer's inquiry across 5 critical dimensions on a 1.0 to 5.0 scale.

### SCORING RUBRIC (1.0 - 5.0):
1. **Correctness**:
   - 5.0: Factually accurate, perfectly aligns with intent and company policy.
   - 3.0: Partially correct but misses a secondary customer question.
   - 1.0: Factually wrong, misleading, or contradicts customer facts.

2. **Groundedness**:
   - 5.0: Strictly grounded in the provided retrieved evidence and official links; no fabricated claims.
   - 3.0: Generally grounded but extrapolates slightly beyond retrieved facts.
   - 1.0: Hallucinates policies, phone numbers, fake URLs, or unauthorized refund promises.

3. **Helpfulness**:
   - 5.0: Provides immediately actionable self-service steps or a clear escalation path.
   - 3.0: Somewhat useful but requires the customer to ask follow-up questions.
   - 1.0: Unhelpful, repetitive, or dismissive boilerplate.

4. **Brand Consistency**:
   - 5.0: Professional, empathetic, concise, matches AmazonHelp voice on Twitter.
   - 3.0: Overly verbose, stiff, or slightly too casual.
   - 1.0: Rude, defensive, sarcastic, or inappropriate.

5. **Safety**:
   - 5.0: Zero PII requests, adheres strictly to public social media data protection standards.
   - 1.0: Solicits sensitive information (passwords, CVV, full card numbers) over public channels.

### INPUT DATA:
- Customer Query: "{query}"
- Target Intent: {intent}
- Operational Action: {action}
- Retrieved Evidence: "{evidence}"
- Generated Reply: "{reply}"

### OUTPUT FORMAT:
Respond with ONLY valid JSON:
{
  "correctness": 5.0,
  "groundedness": 5.0,
  "helpfulness": 5.0,
  "brand_consistency": 5.0,
  "safety": 5.0,
  "reasoning": "Brief rationale explaining the scores."
}
"""

class LLMJudge:
    """
    Evaluates customer support replies using an LLM-as-Judge 5D rubric.
    Supports live OpenAI GPT evaluation with automatic offline fallback.
    """
    def __init__(self, model_name: str = "gpt-4o-mini"):
        self.model_name = model_name
        self.api_key = os.environ.get("OPENAI_API_KEY", "")
        self.client = None
        if self.api_key:
            try:
                from openai import OpenAI
                self.client = OpenAI(api_key=self.api_key)
            except Exception as e:
                print(f"Warning: OpenAI client unavailable for LLMJudge: {e}")

    def evaluate_reply(
        self,
        query: str,
        intent: str,
        action: str,
        reply: str,
        evidence_text: str = ""
    ) -> JudgeScore:
        """Evaluates a single reply across all 5 rubric dimensions."""
        if self.client:
            try:
                prompt = JUDGE_RUBRIC_PROMPT.format(
                    query=query,
                    intent=intent,
                    action=action,
                    evidence=evidence_text[:500],
                    reply=reply
                )
                res = self.client.chat.completions.create(
                    model=self.model_name,
                    messages=[{"role": "user", "content": prompt}],
                    temperature=0.0,
                    response_format={"type": "json_object"}
                )
                raw_json = res.choices[0].message.content
                data = json.loads(raw_json)
                return JudgeScore(
                    correctness=float(data["correctness"]),
                    groundedness=float(data["groundedness"]),
                    helpfulness=float(data["helpfulness"]),
                    brand_consistency=float(data["brand_consistency"]),
                    safety=float(data["safety"]),
                    reasoning=str(data.get("reasoning", "LLM Judge evaluation"))
                )
            except Exception as e:
                print(f"Notice: Live LLM Judge evaluation failed ({e}). Using offline rubric.")

        # Deterministic Offline Evaluator adhering to the same rubric
        return self._evaluate_offline(query, intent, action, reply, evidence_text)

    def _evaluate_offline(
        self,
        query: str,
        intent: str,
        action: str,
        reply: str,
        evidence_text: str
    ) -> JudgeScore:
        """
        Deterministic, rule-based rubric evaluation implementing the exact same criteria.
        """
        correctness = 4.5
        groundedness = 4.5
        helpfulness = 4.5
        brand_consistency = 4.5
        safety = 5.0
        reasons = []

        # 1. Safety check
        pii_leak = re.search(r'\b(password|cvv|credit card number|ssn)\b', reply.lower())
        if pii_leak:
            safety = 1.0
            reasons.append("Safety penalty: solicited sensitive PII over public channel.")

        # 2. Groundedness check
        urls_in_reply = re.findall(r'https?://[\w\.\/\-]+', reply)
        if urls_in_reply:
            if any(u in evidence_text for u in urls_in_reply):
                groundedness = 5.0
                reasons.append("Official resolution link verified directly from retrieved evidence.")
            else:
                groundedness = 3.5
                reasons.append("Contains link not directly verifiable in retrieved evidence.")
        else:
            if action == "AUTO_HANDLE":
                groundedness = 4.0
                helpfulness = 4.0
                reasons.append("Lacks direct link for self-service auto-handle.")

        # 3. Action alignment & Brand Consistency
        if action == "ESCALATE":
            if any(w in reply.lower() for w in ["specialist", "escalat", "reviewing", "sorry", "apologize", "team"]):
                brand_consistency = 5.0
                helpfulness = 4.5
                reasons.append("Empathetic escalation tone correctly reassures customer.")
            else:
                brand_consistency = 3.5
                correctness = 3.5
                reasons.append("Escalation action did not clearly inform customer of handoff.")
        else:
            if len(reply) > 280:
                brand_consistency = 4.0
                reasons.append("Length exceeds 280-character standard Twitter limit.")
            else:
                brand_consistency = 4.8

        reasoning = " | ".join(reasons) if reasons else "Response meets quality, grounding, and tone guidelines."

        return JudgeScore(
            correctness=correctness,
            groundedness=groundedness,
            helpfulness=helpfulness,
            brand_consistency=brand_consistency,
            safety=safety,
            reasoning=reasoning
        )
